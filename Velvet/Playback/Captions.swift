import Foundation
import OSLog

nonisolated struct CaptionTrack: Identifiable, Hashable, Sendable {
    /// yt-dlp's key, e.g. "en", "en-orig", "de".
    let id: String
    let languageCode: String
    let label: String
    let url: URL
    let isAutoGenerated: Bool
}

nonisolated enum CaptionParser {
    /// Manual tracks, then the original-language auto track, then (if different) an auto
    /// translation into `preferredLanguage`. YouTube offers ~150 machine translations; the
    /// menu only needs the useful ones.
    static func tracks(from json: JSON, preferredLanguage: String) -> [CaptionTrack] {
        func vtt(_ list: JSON) -> URL? {
            list.array.first { $0["ext"].string == "vtt" }.flatMap { VideoParser.url($0["url"].string) }
        }
        var out: [CaptionTrack] = []
        if case .object(let manual) = json["subtitles"] {
            for (key, list) in manual.sorted(by: { $0.key < $1.key }) where key != "live_chat" {
                guard let url = vtt(list) else { continue }
                out.append(CaptionTrack(id: key, languageCode: key, label: list[0]["name"].string ?? key,
                                        url: url, isAutoGenerated: false))
            }
        }
        if case .object(let auto) = json["automatic_captions"] {
            if let (key, list) = auto.first(where: { $0.key.hasSuffix("-orig") }), let url = vtt(list) {
                let lang = String(key.dropLast("-orig".count))
                let name = (list[0]["name"].string ?? lang).replacingOccurrences(of: " (Original)", with: "")
                out.append(CaptionTrack(id: key, languageCode: lang, label: "\(name) (auto-generated)",
                                        url: url, isAutoGenerated: true))
                if lang != preferredLanguage, let t = auto[preferredLanguage], let turl = vtt(t),
                   !out.contains(where: { $0.languageCode == preferredLanguage }) {
                    out.append(CaptionTrack(id: preferredLanguage, languageCode: preferredLanguage,
                                            label: "\(t[0]["name"].string ?? preferredLanguage) (auto-translated)",
                                            url: turl, isAutoGenerated: true))
                }
            }
        }
        return out
    }
}

/// Rewrites YouTube WebVTT into something a regular renderer shows well.
///
/// Auto-generated captions are a "rolling" stream: every line appears in a long cue (with
/// per-word timing tags) and again in a 10 ms cue as the previous line, all pinned left with
/// `align:start position:0%`. Rendered as-is that flickers, double-prints and hugs the left
/// edge. We drop the flash cues, strip the word tags and cue settings, and keep each long
/// cue's two lines (previous + current), which reads like YouTube's own roll-up captions.
nonisolated enum CaptionCleaner {
    static func clean(_ vtt: String, autoGenerated: Bool) -> String {
        var out = "WEBVTT\n\n"
        let blocks = vtt.replacingOccurrences(of: "\r\n", with: "\n").components(separatedBy: "\n\n")
        for block in blocks {
            let lines = block.split(separator: "\n", omittingEmptySubsequences: false).map(String.init)
            guard let timingIndex = lines.firstIndex(where: { $0.contains("-->") }) else { continue }
            let parts = lines[timingIndex].components(separatedBy: "-->")
            guard parts.count == 2 else { continue }
            let start = parts[0].trimmingCharacters(in: .whitespaces)
            let end = String(parts[1].trimmingCharacters(in: .whitespaces).prefix { !$0.isWhitespace })
            if autoGenerated, let s = seconds(start), let e = seconds(end), e - s < 0.05 { continue }

            let text = lines[(timingIndex + 1)...]
                .map { stripTimingTags($0).trimmingCharacters(in: .whitespaces) }
                .filter { !$0.isEmpty }
            guard !text.isEmpty else { continue }
            out += "\(start) --> \(end)\n" + text.joined(separator: "\n") + "\n\n"
        }
        return out
    }

    /// Removes `<00:00:02.840>` word timings and `<c>`/`</c>` (class) tags; keeps <i>, <b>.
    private static func stripTimingTags(_ s: String) -> String {
        s.replacingOccurrences(of: #"<\d{2}:\d{2}:\d{2}\.\d{3}>|</?c(\.[^>]*)?>"#, with: "", options: .regularExpression)
    }

    private static func seconds(_ t: String) -> Double? {
        let p = t.split(separator: ":").compactMap { Double($0) }
        guard p.count >= 2 else { return nil }
        return p.reduce(0) { $0 * 60 + $1 }
    }
}

/// Downloads a caption track, cleans it, and stores it as a local file for mpv.
nonisolated enum CaptionLoader {
    static let directory: URL = FileManager.default.urls(for: .cachesDirectory, in: .userDomainMask)[0]
        .appending(path: "com.subhash.Velvet/captions", directoryHint: .isDirectory)

    static func localFile(for track: CaptionTrack, videoId: String) async throws -> URL {
        try? FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        let file = directory.appending(path: "\(videoId)-\(track.id).vtt")
        if FileManager.default.fileExists(atPath: file.path) { return file }
        let (data, response) = try await URLSession.shared.data(from: track.url)
        guard (response as? HTTPURLResponse)?.statusCode == 200 else { throw URLError(.badServerResponse) }
        let cleaned = CaptionCleaner.clean(String(decoding: data, as: UTF8.self), autoGenerated: track.isAutoGenerated)
        try Data(cleaned.utf8).write(to: file, options: .atomic)
        return file
    }
}
